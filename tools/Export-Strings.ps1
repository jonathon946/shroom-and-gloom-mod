# Writes every phrase the mod speaks in its own words, as "key = English", to
# mod\ShroomAccess\data\strings-template.txt. A translator copies it to strings.txt, translates the
# right-hand sides (keeping {0}, {1} in place), and puts it in Mods\ShroomAccess\ in the game.
# Fails if one key is given two different English texts.
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$src = Join-Path $root 'mod\ShroomAccess'
$out = Join-Path $src 'data\strings-template.txt'

$pattern = 'Loc\.T\(\s*"([A-Za-z0-9_.]+)"\s*,\s*"((?:[^"\\]|\\.)*)"'
$seen = [ordered]@{}
$clash = $false
foreach ($file in Get-ChildItem $src -Recurse -Filter *.cs | Where-Object { $_.FullName -notlike '*\bin\*' -and $_.FullName -notlike '*\obj\*' } | Sort-Object Name) {
    $text = Get-Content $file.FullName -Raw
    foreach ($m in [regex]::Matches($text, $pattern)) {
        $key = $m.Groups[1].Value
        $english = $m.Groups[2].Value -replace '\\"', '"' -replace '\\\\', '\'
        if ($seen.Contains($key) -and $seen[$key] -ne $english) {
            Write-Host "Key $key has two texts: '$($seen[$key])' and '$english' ($($file.Name))"
            $clash = $true
        }
        if (-not $seen.Contains($key)) { $seen[$key] = $english }
    }
}
if ($clash) { exit 1 }

$lines = @(
    '# Shroom Access: everything the mod says in its own words, in English.',
    '# To translate: copy this file to strings.txt, change the text after " = " on each line, keep',
    '# {0}, {1} and so on where the values go, and put strings.txt in the game folder under',
    '# Mods\ShroomAccess\. Lines you leave out are said in English. Generated by tools\Export-Strings.ps1.',
    ''
)
foreach ($key in $seen.Keys) { $lines += "$key = $($seen[$key])" }
Set-Content -Path $out -Value $lines -Encoding UTF8
Write-Host "STRINGS $($seen.Count) -> $out"
